import { chromium } from 'playwright';
import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
const base = process.env.PREVIEW_URL || 'http://127.0.0.1:4321';
const browser = await chromium.launch({ headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 1100 }, colorScheme: 'light', reducedMotion: 'reduce', permissions: ['clipboard-read', 'clipboard-write'] });
const page = await context.newPage();
const errors = [];
page.on('pageerror', error => errors.push(error.message));
await fs.mkdir('test-results', { recursive: true });
try {
  assert.equal((await page.goto(base)).status(), 200);
  assert.equal(await page.locator('.post-card').count(), 3);
  await page.screenshot({ path: 'test-results/home-desktop.png', fullPage: true });
  await page.getByRole('button', { name: '切换深色模式' }).click();
  assert.equal(await page.locator('html').getAttribute('data-theme'), 'dark');
  await page.reload();
  assert.equal(await page.locator('html').getAttribute('data-theme'), 'dark');
  await page.getByRole('button', { name: '切换浅色模式' }).click();
  await page.getByRole('button', { name: '搜索文章' }).click();
  await page.locator('#search input').waitFor();
  await page.locator('#search input').fill('公式');
  await page.locator('.pagefind-ui__result-link').first().waitFor();
  assert.match(await page.locator('#search').textContent(), /写作的工作台/);
  await page.screenshot({ path: 'test-results/search.png' });
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('#search-dialog').evaluate(element => element.open), false);
  await page.goto(`${base}/posts/writing-workbench/`);
  await page.waitForFunction(() => document.querySelectorAll('.diagram-canvas svg').length === 2);
  assert.ok(await page.locator('.katex').count() >= 3);
  assert.equal(await page.locator('.diagram-error').count(), 0);
  await page.locator('[data-copy-code]').first().click();
  assert.match(await page.evaluate(() => navigator.clipboard.readText()), /class Observation/);
  const image = page.locator('.prose img').first();
  assert.ok((await image.getAttribute('srcset')).includes('1280w'));
  await image.click();
  assert.equal(await page.locator('#image-dialog').evaluate(element => element.open), true);
  await page.locator('#full-image').evaluate(async element => { await element.decode(); });
  assert.equal(await page.locator('#full-image').evaluate(element => element.naturalWidth), 3200);
  await page.keyboard.press('Escape');
  const svg = page.locator('.diagram-canvas svg').first();
  const before = await svg.evaluate(element => element.getBoundingClientRect().width);
  await page.getByRole('button', { name: '放大流程图' }).first().click();
  const after = await svg.evaluate(element => element.getBoundingClientRect().width);
  assert.ok(after > before);
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: 'SVG ↓' }).first().click();
  assert.match((await downloadPromise).suggestedFilename(), /\.svg$/);
  await page.screenshot({ path: 'test-results/article-desktop.png', fullPage: true });
  await page.getByRole('button', { name: '切换深色模式' }).click();
  await page.waitForFunction(() => document.querySelectorAll('.diagram-canvas svg').length === 2);
  await page.screenshot({ path: 'test-results/article-dark.png', fullPage: true });
  for (const route of ['/archive/', '/tags/', '/tags/科学/', '/about/', '/rss.xml', '/robots.txt', '/sitemap-index.xml']) {
    assert.equal((await page.goto(`${base}${route}`)).status(), 200, route);
  }
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto(base);
  await page.getByRole('button', { name: '切换浅色模式' }).click();
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile homepage must not overflow');
  await page.screenshot({ path: 'test-results/home-mobile.png', fullPage: true });
  await page.goto(`${base}/posts/writing-workbench/`);
  await page.waitForFunction(() => document.querySelectorAll('.diagram-canvas svg').length === 2);
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile article must not overflow');
  await page.screenshot({ path: 'test-results/article-mobile.png', fullPage: true });
  assert.deepEqual(errors, []);
  console.log('Browser checks passed: desktop/mobile layout, theme persistence, Chinese search, code copy, KaTeX, Mermaid/ELK, SVG download, high-resolution image viewer, site routes.');
} finally { await browser.close(); }
